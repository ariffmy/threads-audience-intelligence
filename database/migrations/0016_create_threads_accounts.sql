CREATE TABLE threads_accounts (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    organization_id BIGINT UNSIGNED NOT NULL,
    scope_key CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    provider VARCHAR(16) NOT NULL DEFAULT 'threads',
    environment VARCHAR(16) NOT NULL DEFAULT 'fixture' CHECK (environment='fixture'),
    app_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'fixture-app',
    remote_user_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NULL,
    username VARCHAR(255) NULL,
    profile_expires_at DATETIME(6) NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','active','reauth_required','disconnected','revoked','deleting')),
    privacy_epoch BIGINT UNSIGNED NOT NULL DEFAULT 1,
    credential_generation BIGINT UNSIGNED NOT NULL DEFAULT 1,
    grant_revision BIGINT UNSIGNED NOT NULL DEFAULT 1,
    token_expires_at DATETIME(6) NULL,
    permission_expires_at DATETIME(6) NULL,
    last_sync_at DATETIME(6) NULL,
    safe_error_code VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    blocked_at DATETIME(6) NULL,
    request_key CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    request_until DATETIME(6) NULL,
    next_allowed_at DATETIME(6) NULL,
    window_started_at DATETIME(6) NULL,
    window_requests SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY uq_threads_org (organization_id),
    UNIQUE KEY uq_threads_account (organization_id,id),
    UNIQUE KEY uq_threads_scope (organization_id,scope_key),
    UNIQUE KEY uq_threads_identity (organization_id,environment,app_id,remote_user_id),
    KEY ix_threads_expiry (organization_id,token_expires_at,id),
    CONSTRAINT fk_threads_org FOREIGN KEY (organization_id) REFERENCES organizations(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
