CREATE TABLE jobs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    organization_id BIGINT UNSIGNED NOT NULL,
    job_type VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    payload_version SMALLINT UNSIGNED NOT NULL DEFAULT 1 CHECK (payload_version=1),
    payload_json JSON NOT NULL CHECK (OCTET_LENGTH(payload_json)<=2048),
    dispatch_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ready' CHECK (status IN ('ready','running','retry_wait','succeeded','failed','cancelled')),
    priority SMALLINT NOT NULL DEFAULT 0,
    attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    max_attempts SMALLINT UNSIGNED NOT NULL CHECK (max_attempts BETWEEN 1 AND 10),
    available_at DATETIME(6) NOT NULL,
    lease_token_hash BINARY(32) NULL,
    claim_generation BIGINT UNSIGNED NOT NULL DEFAULT 0,
    lease_expires_at DATETIME(6) NULL,
    scope_privacy_epoch BIGINT UNSIGNED NOT NULL,
    checkpoint_json JSON NULL CHECK (OCTET_LENGTH(checkpoint_json)<=2048),
    safe_error_code VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    finished_at DATETIME(6) NULL,
    expires_at DATETIME(6) NOT NULL,
    UNIQUE KEY uq_job_org_id (organization_id,id),
    UNIQUE KEY uq_job_dispatch (organization_id,dispatch_key),
    KEY ix_job_due (organization_id,status,available_at,priority,id),
    KEY ix_job_lease (organization_id,status,lease_expires_at,id),
    KEY ix_job_expiry (organization_id,expires_at,id),
    KEY ix_job_created (organization_id,created_at,id),
    CONSTRAINT fk_job_scope FOREIGN KEY (organization_id) REFERENCES privacy_scopes(organization_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
