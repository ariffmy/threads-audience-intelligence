CREATE TABLE content_items (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    organization_id BIGINT UNSIGNED NOT NULL,
    threads_account_id BIGINT UNSIGNED NOT NULL,
    remote_media_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    kind VARCHAR(16) NOT NULL CHECK (kind IN ('owned_post','reply')),
    root_id BIGINT UNSIGNED NULL,
    root_remote_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NULL,
    parent_remote_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NULL,
    author_user_id VARCHAR(191) CHARACTER SET ascii COLLATE ascii_bin NULL CHECK (author_user_id IS NULL),
    username VARCHAR(255) NULL,
    body TEXT NULL CHECK (OCTET_LENGTH(body)<=16384),
    permalink VARCHAR(2048) NULL,
    posted_at DATETIME(6) NULL,
    source_version BIGINT UNSIGNED NOT NULL DEFAULT 1,
    content_hash BINARY(32) NOT NULL,
    suppression_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    provenance_json JSON NOT NULL CHECK (OCTET_LENGTH(provenance_json)<=2048),
    first_collected_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    last_verified_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    expires_at DATETIME(6) NOT NULL,
    blocked_at DATETIME(6) NULL,
    UNIQUE KEY uq_content_scope_id (organization_id,threads_account_id,id),
    UNIQUE KEY uq_content_remote (organization_id,threads_account_id,remote_media_id),
    KEY ix_content_root (organization_id,threads_account_id,root_id,id),
    KEY ix_content_expiry (organization_id,threads_account_id,expires_at,id),
    KEY ix_content_suppression (organization_id,threads_account_id,suppression_hash),
    CONSTRAINT fk_content_account FOREIGN KEY (organization_id,threads_account_id) REFERENCES threads_accounts(organization_id,id),
    CONSTRAINT fk_content_root FOREIGN KEY (organization_id,threads_account_id,root_id) REFERENCES content_items(organization_id,threads_account_id,id),
    CHECK ((kind='owned_post' AND root_id IS NULL) OR (kind='reply' AND root_id IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
