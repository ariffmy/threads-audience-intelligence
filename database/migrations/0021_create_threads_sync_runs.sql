CREATE TABLE threads_sync_runs (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    organization_id BIGINT UNSIGNED NOT NULL,
    threads_account_id BIGINT UNSIGNED NOT NULL,
    mode VARCHAR(16) NOT NULL CHECK (mode IN ('posts','replies','conversation')),
    root_id BIGINT UNSIGNED NULL,
    root_version BIGINT UNSIGNED NULL,
    window_start DATETIME(6) NOT NULL,
    window_end DATETIME(6) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','running','partial','exhausted','blocked','failed','cancelled')),
    pages SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    records_seen INT UNSIGNED NOT NULL DEFAULT 0,
    records_retained INT UNSIGNED NOT NULL DEFAULT 0,
    unknown_time INT UNSIGNED NOT NULL DEFAULT 0,
    safe_error_code VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
    privacy_epoch BIGINT UNSIGNED NOT NULL,
    credential_generation BIGINT UNSIGNED NOT NULL,
    grant_revision BIGINT UNSIGNED NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    expires_at DATETIME(6) NOT NULL,
    UNIQUE KEY uq_threads_run_scope (organization_id,threads_account_id,id),
    KEY ix_threads_run_status (organization_id,threads_account_id,status,id),
    KEY ix_threads_run_expiry (organization_id,expires_at,id),
    CONSTRAINT fk_threads_run_account FOREIGN KEY (organization_id,threads_account_id) REFERENCES threads_accounts(organization_id,id),
    CONSTRAINT fk_threads_run_root FOREIGN KEY (organization_id,threads_account_id,root_id) REFERENCES content_items(organization_id,threads_account_id,id),
    CHECK (window_end>window_start AND TIMESTAMPDIFF(SECOND,window_start,window_end)<=2592000),
    CHECK ((mode='posts' AND root_id IS NULL) OR (mode<>'posts' AND root_id IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
